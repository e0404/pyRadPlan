"""Dynamically generated configuration forms for algorithm config models.

Builds a Qt form from the fields of an :class:`~pyRadPlan.core.AlgorithmConfig`
subclass (as generated by :meth:`~pyRadPlan.core.ConfigurableAlgorithm.config_model`),
mapping field types and constraints to suitable editor widgets. Edits are
validated live through a draft model instance (``validate_assignment``), so
invalid values are flagged without ever producing an inconsistent config.

Fields holding a dataclass (e.g. ``ipax.Options``) are edited in collapsible
sub-forms; their edits are reported as a nested dictionary of overrides, see
:func:`~pyRadPlan.core.replace_nested`.
"""

from __future__ import annotations

import dataclasses
import json
import logging
import types
from copy import deepcopy
from typing import (
    Any,
    Callable,
    Literal,
    Mapping,
    Optional,
    Union,
    get_args,
    get_origin,
    get_type_hints,
)

from pydantic import BaseModel, ValidationError
from PySide6.QtCore import Qt, Signal
from PySide6.QtWidgets import (
    QCheckBox,
    QComboBox,
    QDialog,
    QDialogButtonBox,
    QFormLayout,
    QLabel,
    QLineEdit,
    QScrollArea,
    QSpinBox,
    QToolButton,
    QVBoxLayout,
    QWidget,
)

from pyRadPlan.core import AlgorithmConfig, field_constraints, replace_nested
from ._base import AdaptiveDoubleSpinBox, parse_number_list

logger = logging.getLogger(__name__)

_INT_LIMIT = 2**31 - 1
_FLOAT_LIMIT = 1e12
_UNION_TYPES = (Union, types.UnionType)


def _unwrap_optional(annotation: Any) -> tuple[Any, bool]:
    """Strip Optional[...] from an annotation, returning (inner, was_optional)."""
    if get_origin(annotation) in _UNION_TYPES:
        args = [a for a in get_args(annotation) if a is not type(None)]
        if len(args) == 1:
            return args[0], True
        return annotation, type(None) in get_args(annotation)
    return annotation, False


def _literal_choices(annotation: Any) -> tuple[tuple, bool]:
    """Choices of the Literal members of a union, and whether it also admits any string."""
    if get_origin(annotation) not in _UNION_TYPES:
        return (), False
    members = get_args(annotation)
    choices = tuple(c for m in members if get_origin(m) is Literal for c in get_args(m))
    return choices, str in members


def _is_dataclass_instance(value: Any) -> bool:
    return dataclasses.is_dataclass(value) and not isinstance(value, type)


class _CollapsibleSection(QWidget):
    """A titled, initially collapsed section holding a form layout."""

    def __init__(self, title: str, parent: Optional[QWidget] = None) -> None:
        super().__init__(parent)
        layout = QVBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)
        layout.setSpacing(2)

        self.toggle = QToolButton()
        self.toggle.setText(title)
        self.toggle.setCheckable(True)
        self.toggle.setAutoRaise(True)
        self.toggle.setToolButtonStyle(Qt.ToolButtonStyle.ToolButtonTextBesideIcon)
        self.toggle.setArrowType(Qt.ArrowType.RightArrow)
        layout.addWidget(self.toggle)

        self.body = QWidget()
        self.form = QFormLayout(self.body)
        self.form.setContentsMargins(16, 0, 0, 0)
        self.form.setVerticalSpacing(4)
        self.body.setVisible(False)
        layout.addWidget(self.body)

        self.toggle.toggled.connect(self._set_expanded)

    def _set_expanded(self, expanded: bool) -> None:
        self.body.setVisible(expanded)
        self.toggle.setArrowType(Qt.ArrowType.DownArrow if expanded else Qt.ArrowType.RightArrow)


class ConfigFormWidget(QWidget):
    """Auto-generated editor form for an :class:`AlgorithmConfig` subclass.

    Parameters
    ----------
    model_cls:
        The configuration model class (``SomeEngine.config_model()``).
    initial:
        Initial values (e.g. the current ``pln.prop_dose_calc`` entries).
        Invalid entries are dropped with a log message.  For a field holding a
        dataclass, a mapping is taken as nested overrides of its default.
    exclude:
        Field names to leave out of the form (e.g. nested sub-configurations
        that are edited elsewhere).
    parent:
        Optional Qt parent widget.
    defaults:
        Values shown for fields absent from *initial*, e.g. the effective
        defaults of an algorithm instance where the class declares none.
        Unlike *initial*, they are not reported by :meth:`values` unless edited.
    """

    #: Emitted with (field_name, value) after a successful edit.
    value_changed = Signal(str, object)
    #: Emitted with (field_name, message) when an edit fails validation.
    validation_failed = Signal(str, str)

    def __init__(
        self,
        model_cls: type[AlgorithmConfig],
        initial: Optional[Mapping[str, Any]] = None,
        exclude: Optional[set[str]] = None,
        parent: Optional[QWidget] = None,
        defaults: Optional[Mapping[str, Any]] = None,
    ) -> None:
        super().__init__(parent)
        self._model_cls = model_cls
        self._exclude = set(exclude or ())
        self._editors: dict[str, QWidget] = {}
        #: Overrides of each dataclass-valued field, edited through its sub-form.
        self._nested: dict[str, dict] = {}
        #: Value of each dataclass-valued field its overrides apply to.
        self._nested_base: dict[str, Any] = {}

        defaults = self._valid_entries(model_cls, dict(defaults or {}), log=False)
        initial = dict(initial or {})
        for name, value in list(initial.items()):
            if name not in model_cls.model_fields or not isinstance(value, Mapping):
                continue
            default = defaults.get(name)
            if default is None:
                default = model_cls.model_fields[name].get_default(call_default_factory=True)
            if _is_dataclass_instance(default):
                self._nested[name] = deepcopy(dict(initial.pop(name)))
        initial = self._valid_entries(model_cls, initial, log=True)
        #: Fields reported by values(): set initially or edited since.
        self._explicit: set[str] = set(initial)
        self._draft = model_cls.model_construct(**{**defaults, **initial})

        form = QFormLayout(self)
        form.setContentsMargins(0, 0, 0, 0)
        form.setVerticalSpacing(4)

        for name, info in model_cls.model_fields.items():
            if name in self._exclude:
                continue
            editor = self._create_editor(name, info)
            if editor is None:
                continue
            self._editors[name] = editor
            if isinstance(editor, _CollapsibleSection):
                form.addRow(editor)
            else:
                form.addRow(QLabel(self._label_for(name, info)), editor)

        if not self._editors:
            form.addRow(QLabel("No configurable parameters."))

    @staticmethod
    def _valid_entries(
        model_cls: type[BaseModel], values: dict[str, Any], log: bool
    ) -> dict[str, Any]:
        """Validate entries of *values* by field name, dropping invalid ones."""
        try:
            validated = model_cls.model_validate(values)
        except ValidationError as exc:
            if log:
                logger.info(
                    "Some initial values are invalid for %s and will be ignored: %s",
                    model_cls.__name__,
                    exc,
                )
        else:
            return {name: getattr(validated, name) for name in validated.model_fields_set}

        entries = {}
        for key, value in values.items():
            try:
                validated = model_cls.model_validate({key: value})
            except ValidationError:
                continue
            entries.update({name: getattr(validated, name) for name in validated.model_fields_set})
        return entries

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    @property
    def model_cls(self) -> type[AlgorithmConfig]:
        """The configuration model class this form edits."""
        return self._model_cls

    def config(self) -> AlgorithmConfig:
        """Get the draft model instance holding the current form state."""
        return self._draft

    def values(self) -> dict[str, Any]:
        """Get the entries that were set initially or edited by the user.

        A dataclass-valued field is reported as the nested dictionary of its
        overrides, or as the updated dataclass if one was given initially.
        """
        values = {
            name: getattr(self._draft, name)
            for name in self._explicit
            if name not in self._exclude and name not in self._nested_base
        }
        for name in self._nested_base:
            if name in self._explicit or self._nested.get(name):
                values[name] = self._nested_value(name)
        return values

    # ------------------------------------------------------------------
    # Editor construction
    # ------------------------------------------------------------------

    @staticmethod
    def _label_for(name: str, info) -> str:
        meta = field_constraints(info).get("param_meta")
        if meta is not None and meta.label:
            return meta.label
        return name.replace("_", " ").capitalize() + ":"

    def _create_editor(self, name: str, info) -> Optional[QWidget]:
        constraints = field_constraints(info)
        meta = constraints.get("param_meta")
        if meta is not None and not meta.configurable:
            return None

        value = getattr(self._draft, name)
        if _is_dataclass_instance(value):
            hidden = meta.hidden_entries if meta is not None else frozenset()
            editor = self._make_dataclass_editor(name, value, self._label_for(name, info), hidden)
        else:
            annotation, optional = _unwrap_optional(info.annotation)
            editor = self._editor_for(
                name,
                annotation,
                value,
                optional,
                constraints,
                lambda v, name=name: self._set_value(name, v),
            )

        if constraints.get("description"):
            editor.setToolTip(constraints["description"])
        return editor

    def _editor_for(
        self,
        key: str,
        annotation: Any,
        value: Any,
        optional: bool,
        constraints: dict,
        commit: Callable[[Any], None],
    ) -> QWidget:
        """Editor widget for a value of type *annotation*, committing edits through *commit*."""
        origin = get_origin(annotation)
        choices, any_text = _literal_choices(annotation)
        if annotation is bool:
            return self._make_bool_editor(value, commit)
        if annotation in (int, float) and optional and value is None:
            # A spin box cannot show "unset", so None keeps a blank text field.
            return self._make_optional_number_editor(key, annotation, commit)
        if annotation is int:
            return self._make_int_editor(value, constraints, commit)
        if annotation is float:
            return self._make_float_editor(value, constraints, commit)
        if origin is Literal:
            return self._make_choice_editor(value, get_args(annotation), commit)
        if choices and (value is None or isinstance(value, str)):
            return self._make_choice_editor(value, choices, commit, editable=any_text)
        if annotation is str:
            return self._make_str_editor(value, optional, commit)
        if origin is list and get_args(annotation) and get_args(annotation)[0] in (int, float):
            return self._make_list_editor(key, value, get_args(annotation)[0], commit)
        # Unsupported field types get a generic JSON editor instead of
        # silently disappearing from the form.
        return self._make_fallback_editor(value, commit)

    def _make_bool_editor(self, value: Any, commit: Callable[[Any], None]) -> QCheckBox:
        box = QCheckBox()
        box.setChecked(bool(value))
        box.toggled.connect(commit)
        return box

    def _make_int_editor(
        self, value: Any, constraints: dict, commit: Callable[[Any], None]
    ) -> QSpinBox:
        spin = QSpinBox()
        low = constraints.get("ge", constraints.get("gt", -_INT_LIMIT))
        high = constraints.get("le", constraints.get("lt", _INT_LIMIT))
        if "gt" in constraints:
            low = constraints["gt"] + 1
        if "lt" in constraints:
            high = constraints["lt"] - 1
        spin.setRange(int(low), int(high))
        if value is not None:
            spin.setValue(int(value))
        spin.valueChanged.connect(commit)
        return spin

    def _make_float_editor(
        self, value: Any, constraints: dict, commit: Callable[[Any], None]
    ) -> AdaptiveDoubleSpinBox:
        spin = AdaptiveDoubleSpinBox()
        low = constraints.get("ge", constraints.get("gt", -_FLOAT_LIMIT))
        high = constraints.get("le", constraints.get("lt", _FLOAT_LIMIT))
        spin.setRange(float(low), float(min(high, _FLOAT_LIMIT)))
        if value is not None:
            spin.setValue(float(min(value, _FLOAT_LIMIT)))
        spin.valueChanged.connect(commit)
        return spin

    def _make_optional_number_editor(
        self, key: str, number_type: type, commit: Callable[[Any], None]
    ) -> QLineEdit:
        edit = QLineEdit()
        edit.setPlaceholderText("None")

        def _commit() -> None:
            text = edit.text().strip()
            try:
                commit(number_type(text) if text else None)
            except ValueError as exc:
                self._flag_error(key, str(exc))

        edit.editingFinished.connect(_commit)
        return edit

    def _make_choice_editor(
        self,
        value: Any,
        choices: tuple,
        commit: Callable[[Any], None],
        editable: bool = False,
    ) -> QComboBox:
        combo = QComboBox()
        combo.setEditable(editable)
        combo.addItems([str(c) for c in choices])
        if value is not None:
            combo.setCurrentText(str(value))
        combo.currentTextChanged.connect(commit)
        return combo

    def _make_str_editor(
        self, value: Any, optional: bool, commit: Callable[[Any], None]
    ) -> QLineEdit:
        edit = QLineEdit(str(value) if value is not None else "")
        if optional:
            edit.editingFinished.connect(lambda: commit(edit.text() or None))
        else:
            edit.editingFinished.connect(lambda: commit(edit.text()))
        return edit

    def _make_list_editor(
        self, key: str, value: Any, item_type: type, commit: Callable[[Any], None]
    ) -> QLineEdit:
        text = " ".join(f"{v:g}" for v in value) if value else ""
        edit = QLineEdit(text)

        def _commit() -> None:
            try:
                parsed = parse_number_list(edit.text(), item_type)
            except ValueError as exc:
                self._flag_error(key, str(exc))
                return
            commit(parsed)

        edit.editingFinished.connect(_commit)
        return edit

    def _make_fallback_editor(self, value: Any, commit: Callable[[Any], None]) -> QLineEdit:
        try:
            text = json.dumps(value) if value is not None else ""
        except (TypeError, ValueError):
            text = str(value)
        edit = QLineEdit(text)

        def _commit() -> None:
            raw = edit.text().strip()
            if not raw:
                commit(None)
                return
            try:
                parsed = json.loads(raw)
            except ValueError:
                parsed = raw  # plain strings need no quoting
            commit(parsed)

        edit.editingFinished.connect(_commit)
        return edit

    # ------------------------------------------------------------------
    # Dataclass-valued fields
    # ------------------------------------------------------------------

    def _make_dataclass_editor(
        self, name: str, base: Any, label: str, hidden: frozenset[str] = frozenset()
    ) -> _CollapsibleSection:
        self._nested_base[name] = base
        overrides = self._nested.setdefault(name, {})
        try:
            shown = self._validated_nested(name, base, overrides)
        except (TypeError, ValueError) as exc:
            logger.info("Ignoring invalid initial overrides of %s: %s", name, exc)
            overrides.clear()
            shown = base
        setattr(self._draft, name, shown)
        section = _CollapsibleSection(label.rstrip(":"))
        self._fill_dataclass_form(section.form, name, (), shown, hidden)
        return section

    def _fill_dataclass_form(
        self,
        form: QFormLayout,
        name: str,
        path: tuple[str, ...],
        obj: Any,
        hidden: frozenset[str],
    ) -> None:
        try:
            hints = get_type_hints(type(obj))
        except Exception:  # noqa: BLE001 - unresolvable hints only cost the dedicated widgets
            hints = {}
        for field in dataclasses.fields(obj):
            if not field.init:
                continue
            field_path = (*path, field.name)
            if ".".join(field_path) in hidden:
                continue
            label = field.name.replace("_", " ").capitalize()
            value = getattr(obj, field.name)
            if _is_dataclass_instance(value):
                section = _CollapsibleSection(label)
                self._fill_dataclass_form(section.form, name, field_path, value, hidden)
                form.addRow(section)
                continue
            key = ".".join((name, *field_path))
            annotation, optional = _unwrap_optional(hints.get(field.name, Any))
            editor = self._editor_for(
                key,
                annotation,
                value,
                optional,
                {},
                lambda v, p=field_path: self._set_nested(name, p, v),
            )
            self._editors[key] = editor
            form.addRow(QLabel(label + ":"), editor)

    def _set_nested(self, name: str, path: tuple[str, ...], value: Any) -> None:
        overrides = deepcopy(self._nested.get(name, {}))
        node = overrides
        for key in path[:-1]:
            child = node.get(key)
            if not isinstance(child, dict):
                child = node[key] = {}
            node = child
        node[path[-1]] = value
        key = ".".join((name, *path))
        try:
            updated = self._validated_nested(name, self._nested_base[name], overrides)
            setattr(self._draft, name, updated)
        except (TypeError, ValueError) as exc:
            self._flag_error(key, str(exc))
            return
        self._nested[name] = overrides
        editor = self._editors.get(key)
        if editor is not None:
            editor.setStyleSheet("")
        self.value_changed.emit(name, self._nested_value(name))

    def _validated_nested(self, name: str, base: Any, overrides: dict) -> Any:
        """Validate a complete options tree before accepting any of its overrides."""
        updated = replace_nested(base, overrides)
        # Validate a mapping so pydantic checks the dataclass's field types as well
        # as its __post_init__; existing dataclass instances are not revalidated.
        validated = self._model_cls.model_validate({name: dataclasses.asdict(updated)})
        value = getattr(validated, name)
        # Unsupported dataclass schemas may have been degraded to Any by config_model.
        return value if _is_dataclass_instance(value) else updated

    def _nested_value(self, name: str) -> Any:
        """Return a dataclass field's value as reported by :meth:`values`."""
        overrides = self._nested.get(name, {})
        if name in self._explicit:
            return getattr(self._draft, name)
        return deepcopy(overrides)

    # ------------------------------------------------------------------
    # Draft synchronisation
    # ------------------------------------------------------------------

    def _set_value(self, name: str, value: Any) -> None:
        try:
            setattr(self._draft, name, value)
        except ValidationError as exc:
            self._flag_error(name, exc.errors()[0]["msg"] if exc.errors() else str(exc))
            return
        self._explicit.add(name)
        editor = self._editors.get(name)
        if editor is not None:
            editor.setStyleSheet("")
        self.value_changed.emit(name, value)

    def _flag_error(self, name: str, message: str) -> None:
        editor = self._editors.get(name)
        if editor is not None:
            editor.setStyleSheet("border: 1px solid red;")
            editor.setToolTip(message)
        self.validation_failed.emit(name, message)


class ConfigFormDialog(QDialog):
    """Modal popup wrapping a :class:`ConfigFormWidget` with OK/Cancel buttons.

    Parameters
    ----------
    model_cls:
        The configuration model class (``SomeEngine.config_model()``).
    initial:
        Initial values shown in the form.
    title:
        Window title (e.g. ``"Configure SVD Pencil Beam"``).
    parent:
        Optional Qt parent widget.
    """

    def __init__(
        self,
        model_cls: type[AlgorithmConfig],
        initial: Optional[Mapping[str, Any]] = None,
        title: str = "Configure",
        parent: Optional[QWidget] = None,
    ) -> None:
        super().__init__(parent)
        self.setWindowTitle(title)

        root = QVBoxLayout(self)
        self._form = ConfigFormWidget(model_cls, initial=initial)

        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setFrameShape(QScrollArea.Shape.NoFrame)
        scroll.setWidget(self._form)
        root.addWidget(scroll, 1)

        self._lbl_status = QLabel("")
        self._lbl_status.setStyleSheet("color: red;")
        root.addWidget(self._lbl_status)
        self._form.validation_failed.connect(
            lambda name, msg: self._lbl_status.setText(f"{name}: {msg}")
        )
        self._form.value_changed.connect(lambda *_: self._lbl_status.setText(""))

        buttons = QDialogButtonBox(
            QDialogButtonBox.StandardButton.Ok | QDialogButtonBox.StandardButton.Cancel
        )
        buttons.accepted.connect(self.accept)
        buttons.rejected.connect(self.reject)
        root.addWidget(buttons)

        self.resize(420, min(120 + 28 * len(self._form._editors), 600))

    @property
    def form(self) -> ConfigFormWidget:
        """Get the embedded configuration form."""
        return self._form

    def values(self) -> dict[str, Any]:
        """Get the entries that were set initially or edited by the user."""
        return self._form.values()
