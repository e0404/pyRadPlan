/**
 * Third-party notices of the web build, generated from what the build actually ships.
 *
 * `thirdPartyNotices()` returns two Vite plugins: `worker` records the modules of the worker
 * bundles, `main` those of the app bundle and then writes `THIRD_PARTY_NOTICES.txt` (and
 * pyRadPlan's own `LICENSE.txt`) into the output. A module counts when its id lies in a
 * `node_modules/<package>/` directory; its package's `LICENSE*` / `LICENCE*` / `COPYING*` /
 * `NOTICE*` files are copied verbatim. Files shipped next to the bundle (the Pyodide runtime,
 * the optional service worker) are given as `extras`. A package without a license file falls back
 * to `licenses/<name>.txt`; when that is missing too, the build fails.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { Plugin } from "vite";

export interface NoticeEntry {
  name: string;
  version: string;
  license: string;
  homepage: string;
  /** What of it the build contains. */
  usedIn: string;
  text: string;
}

/** A component shipped outside the module graph. */
export interface ExtraComponent {
  name: string;
  usedIn: string;
  /** npm package directory to read `package.json` and license files from. */
  packageDir?: string;
  version?: string;
  license?: string;
  homepage?: string;
  /** License text file used when the package has none (or for non-npm components). */
  textFile?: string;
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([.-].*)?$/i;

/** The npm package a module id belongs to, or `null` for app sources and virtual modules. */
export function packageOfModule(id: string): { name: string; dir: string } | null {
  const clean = id.replace(/^\0/, "").split("?")[0].replace(/\\/g, "/");
  const marker = "/node_modules/";
  const at = clean.lastIndexOf(marker);
  if (at < 0) return null;
  const parts = clean.slice(at + marker.length).split("/");
  const name = parts[0].startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0];
  if (!name) return null;
  return { name, dir: clean.slice(0, at + marker.length) + name };
}

/** License files of a package directory, concatenated (several under their file names). */
export function readLicenseFiles(dir: string): string | null {
  if (!existsSync(dir)) return null;
  const files = readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort();
  const texts = files.map((f) => [f, readFileSync(join(dir, f), "utf8").trim()] as const).filter(([, t]) => t);
  if (!texts.length) return null;
  if (texts.length === 1) return texts[0][1];
  return texts.map(([f, t]) => `${f}\n${"-".repeat(f.length)}\n${t}`).join("\n\n");
}

function packageJson(dir: string): Record<string, unknown> {
  const file = join(dir, "package.json");
  return existsSync(file) ? (JSON.parse(readFileSync(file, "utf8")) as Record<string, unknown>) : {};
}

function homepageOf(pkg: Record<string, unknown>): string {
  if (typeof pkg.homepage === "string") return pkg.homepage;
  const repo = pkg.repository;
  const url = typeof repo === "string" ? repo : typeof repo === "object" && repo ? (repo as { url?: unknown }).url : undefined;
  return typeof url === "string" ? url.replace(/^git\+/, "").replace(/\.git$/, "") : "";
}

/** Resolve one component to a notice entry; throws when no license text can be found. */
export function resolveEntry(component: ExtraComponent, overridesDir: string): NoticeEntry {
  const pkg = component.packageDir ? packageJson(component.packageDir) : {};
  const text =
    (component.packageDir ? readLicenseFiles(component.packageDir) : null) ??
    (component.textFile && existsSync(component.textFile) ? readFileSync(component.textFile, "utf8").trim() : null) ??
    (existsSync(join(overridesDir, `${component.name.replace("/", "__")}.txt`))
      ? readFileSync(join(overridesDir, `${component.name.replace("/", "__")}.txt`), "utf8").trim()
      : null);
  if (!text) {
    throw new Error(
      `No license text for ${component.name} (${component.usedIn}): the package has no LICENSE file and ` +
        `${join(overridesDir, `${component.name.replace("/", "__")}.txt`)} does not exist`,
    );
  }
  return {
    name: component.name,
    version: component.version ?? (typeof pkg.version === "string" ? pkg.version : ""),
    license: component.license ?? (typeof pkg.license === "string" ? pkg.license : "see text"),
    homepage: component.homepage ?? homepageOf(pkg),
    usedIn: component.usedIn,
    text,
  };
}

export function renderNotices(entries: NoticeEntry[]): string {
  const rule = "=".repeat(78);
  const head = [
    "Third-party notices of the pyRadPlan web app",
    "",
    "Generated by the build from the packages in the JavaScript bundle and the files shipped next",
    "to it. pyRadPlan itself is licensed under the BSD 3-Clause License (LICENSE.txt).",
    "",
    "Not listed here: the Python packages (pyRadPlan's wheels in pyrp/ and the Pyodide packages",
    "loaded from cdn.jsdelivr.net). Each carries its license in its wheel; the app lists them",
    "under Help > Third-party Licenses.",
    "",
    "Components:",
    ...entries.map((e) => `  - ${e.name}${e.version ? ` ${e.version}` : ""} (${e.license})`),
    "",
  ];
  const body = entries.map((e) =>
    [
      rule,
      `${e.name}${e.version ? ` ${e.version}` : ""}`,
      `License: ${e.license}`,
      ...(e.homepage ? [`Source: ${e.homepage}`] : []),
      `Contained in: ${e.usedIn}`,
      rule,
      "",
      e.text,
      "",
    ].join("\n"),
  );
  return [...head, ...body].join("\n");
}

export interface NoticeOptions {
  /** `licenses/` directory with fallback texts. */
  overridesDir: string;
  /** pyRadPlan's LICENSE, copied to `LICENSE.txt`. */
  projectLicense: string;
  /** Components shipped outside the module graph, evaluated when the bundle is written. */
  extras: () => ExtraComponent[];
}

export const NOTICES_FILE = "THIRD_PARTY_NOTICES.txt";

export function thirdPartyNotices(options: NoticeOptions): { main: Plugin; worker: Plugin } {
  const packages = new Map<string, { dir: string; usedIn: Set<string> }>();
  const record = (bundle: Record<string, { type: string; moduleIds?: string[] }>, where: string) => {
    for (const output of Object.values(bundle)) {
      if (output.type !== "chunk") continue;
      for (const id of output.moduleIds ?? []) {
        const pkg = packageOfModule(id);
        if (!pkg) continue;
        const entry = packages.get(pkg.name) ?? { dir: pkg.dir, usedIn: new Set<string>() };
        entry.usedIn.add(where);
        packages.set(pkg.name, entry);
      }
    }
  };
  const worker: Plugin = {
    name: "pyradplan-third-party-notices-worker",
    apply: "build",
    generateBundle(_, bundle) {
      record(bundle as never, "the JavaScript bundle (web worker, assets/)");
    },
  };
  const main: Plugin = {
    name: "pyradplan-third-party-notices",
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const path = (req.url ?? "").split("?")[0];
        if (path !== `/${NOTICES_FILE}` && path !== "/LICENSE.txt") return next();
        res.setHeader("Content-Type", "text/plain; charset=utf-8");
        res.end(
          path === "/LICENSE.txt"
            ? readFileSync(options.projectLicense, "utf8")
            : "The third-party notices are generated by the production build (npm run build).\n",
        );
      });
    },
    generateBundle(_, bundle) {
      record(bundle as never, "the JavaScript bundle (assets/)");
      const components: ExtraComponent[] = [...packages.entries()]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([name, { dir, usedIn }]) => ({ name, packageDir: dir, usedIn: [...usedIn].sort().join("; ") }));
      let entries: NoticeEntry[];
      try {
        entries = [...components, ...options.extras()].map((c) => resolveEntry(c, options.overridesDir));
      } catch (err) {
        this.error(err instanceof Error ? err.message : String(err));
      }
      this.emitFile({ type: "asset", fileName: NOTICES_FILE, source: renderNotices(entries) });
      this.emitFile({ type: "asset", fileName: "LICENSE.txt", source: readFileSync(options.projectLicense, "utf8") });
    },
  };
  return { main, worker };
}
