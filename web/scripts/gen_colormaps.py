"""Generate src/renderer/colormapData.ts: 256-entry RGB lookup tables from matplotlib.

The Qt viewer resolves its colormaps with ``pg.colormap.getFromMatplotlib`` and samples
256 entries, so taking the tables from matplotlib keeps both viewers identical.
Run with ``npm run gen:colormaps`` (needs matplotlib).
"""

import base64
from pathlib import Path

import matplotlib
import numpy as np

NAMES = [
    "jet",
    "viridis",
    "magma",
    "plasma",
    "inferno",
    "gray",
    "bone",
    "seismic",
    "coolwarm",
    "RdBu_r",
    "bwr",
    "hot",
    "turbo",
]

out = Path(__file__).resolve().parent.parent / "src" / "renderer" / "colormapData.ts"
lines = [
    "// Generated by scripts/gen_colormaps.py from matplotlib "
    f"{matplotlib.__version__}; do not edit.",
    "// Each entry: base64 of 256 x RGB uint8.",
    "export const COLORMAP_DATA: Record<string, string> = {",
]
for name in NAMES:
    cmap = matplotlib.colormaps[name]
    rgb = (np.asarray(cmap(np.linspace(0.0, 1.0, 256)))[:, :3] * 255.0 + 0.5).astype(np.uint8)
    lines.append(f'  "{name}": "{base64.b64encode(rgb.tobytes()).decode()}",')
lines.append("};")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out}")
