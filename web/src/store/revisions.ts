/** Show `key` (any component key), fetching it first when it is not held yet. */
export async function selectQuantity(key: string | null): Promise<void> {
  const current = get().state?.revisions?.volumes[key ?? ""];
  if (key && (!get().quantities[key] || (current !== undefined && current !== get().appliedRevisions.volumes[key]))) {
    const vol = await req("view.volume", { name: key });
    const rev = get().state?.revisions?.volumes[key] ?? 0;
    set((s) => ({
      quantities: { ...s.quantities, [key]: vol },
      appliedRevisions: { ...s.appliedRevisions, volumes: { ...s.appliedRevisions.volumes, [key]: rev } },
    }));
  }
  set((s) => ({ viewer: { ...s.viewer, activeQuantity: key, quantityWindow: null } }));
}

/** Fetch (or return held) volumes for analysis (DVH needs no volumes; kept for readout). */
export async function fetchBeams(): Promise<void> {
  if (!hasMethod("view.beams") || !get().state?.has.ct) {
    set({ beams: null });
    return;
  }
  const draft = get().draftBeams;
  try {
    const beams = await req("view.beams", draft ? { draft } : {});
    set({ beams });
  } catch (err) {
    console.warn("view.beams failed", err);
    set({ beams: null });
  }
}

/** The plan form reports its edited (unapplied) beam angles; `null` when none. */
export function setDraftBeams(draft: BeamDraft | null): void {
  const prev = get().draftBeams;
  if (JSON.stringify(prev) === JSON.stringify(draft)) return;
  set({ draftBeams: draft });
  void fetchBeams();
}

/**
 * A beam was dragged to `gantry` degrees. Like Qt, the angle goes into the plan form's draft
 * (registered beam editor); without a plan form editor it is applied with `plan.set`.
 */
export async function requestBeamAngle(index: number, gantry: number): Promise<void> {
  const editor = currentBeamEditor();
  if (editor) {
    editor(index, gantry);
    return;
  }
  const plan = get().state?.plan;
  const draft = get().draftBeams;
  const gantryAngles = [...(draft?.gantry_angles ?? plan?.gantry_angles ?? [])];
  if (index < 0 || index >= gantryAngles.length) return;
  gantryAngles[index] = gantry;
  const couch = draft?.couch_angles ?? plan?.couch_angles ?? gantryAngles.map(() => 0);
  const { actions } = await import("./appStore");
  await actions.applyPlan({ gantry_angles: gantryAngles, couch_angles: couch });
}
