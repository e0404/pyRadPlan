/**
 * Revision-driven refetching of the viewer data (PROTOCOL.md v1 `state.revisions`).
 *
 * Every SessionState carries revision counters per workspace key, per volume key, for the masks
 * and for the beams. The data held by the frontend remembers the revisions it was fetched at
 * (`appliedRevisions`); `syncViews` refetches exactly what changed, whatever request or event
 * changed it. A v0 backend has no revisions: then the caller's `force` hint decides (the old
 * method-based behaviour: after `data.*` everything, after optimize / recalc the quantities).
 *
 * Other packages call `syncViews` / `scheduleViewSync`; they do not edit this file.
 */
import { isoCenterPoint } from "../api/protocol";
import type { Method, ParamsOf, ResultOf, SessionState, StructureMasks, Volume, Vec3 } from "../api/protocol";
import type { BeamDraft, BitsMasks, CropMasks } from "../api/protocol/viewer";
import { DEFAULT_VIEW, sliceLayout, slicesThrough, type Plane } from "../renderer/geometry";
import { maskCenterOfMass, type MaskVolume } from "../renderer/contours";
import { defaultQuantityKey, fullKeys, groupResultKeys } from "../results/resultGroups";
import { useApp } from "./appStore";
import { EMPTY_REVISIONS, currentBeamEditor, defaultCheckedVois, type AppliedRevisions, type MaskSet } from "./viewerSlice";

export type SyncForce = "data" | "result" | "all";

// Deferred: appStore imports this module, so `useApp` is not initialized at load time.
const get = () => useApp.getState();
const set = ((...args: Parameters<typeof useApp.setState>) => useApp.setState(...args)) as typeof useApp.setState;

async function req<M extends Method>(method: M, params: ParamsOf<M>): Promise<ResultOf<M>> {
  const { backend, session } = get();
  if (!backend) throw new Error("Backend not connected");
  return backend.request(method, params, session ?? undefined);
}

export function hasMethod(method: string): boolean {
  const methods = get().info?.methods;
  return !methods || methods.includes(method);
}

/** Result groups of the state (v1 `results`, else grouped from the v0 `quantities`). */
export function resultGroups(state: SessionState | null) {
  if (!state) return [];
  return state.results?.groups ?? groupResultKeys(state.quantities);
}

