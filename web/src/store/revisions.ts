/** Normalize any `view.structure_masks` encoding into renderer masks (no full-volume copies). */
export function decodeMasks(result: StructureMasks | BitsMasks | CropMasks): MaskSet {
  const enc = (result as { encoding?: string }).encoding;
  if (enc === "bits") {
    const r = result as BitsMasks;
    return {
      grid: r.grid,
      masks: r.masks.map((m) => ({
        index: m.index,
        name: m.name,
        color: m.color,
        storage: { kind: "bits", plane: r.planes[m.plane].data, bit: m.bit, bbox: m.bbox },
      })),
    };
  }
  if (enc === "crops") {
    const r = result as CropMasks;
    return {
      grid: r.grid,
      masks: r.masks.map(
        (m): MaskVolume =>
          m.bbox && m.data
            ? { index: m.index, name: m.name, color: m.color, storage: { kind: "crop", data: m.data.data, bbox: m.bbox } }
            : { index: m.index, name: m.name, color: m.color, storage: { kind: "bits", plane: new Uint8Array(0), bit: 0, bbox: null } },
      ),
    };
  }
  const r = result as StructureMasks;
  return { grid: r.grid, masks: r.masks.map((m) => ({ index: m.index, name: m.name, color: m.color, data: m.data.data })) };
}

