let running: Promise<void> | null = null;
let again: SyncForce | "plain" | null = null;

function strongest(a: SyncForce | "plain" | null, b: SyncForce | "plain"): SyncForce | "plain" {
  const rank = { plain: 0, result: 1, data: 2, all: 3 } as const;
  return a && rank[a] >= rank[b] ? a : b;
}

/** Bring the viewer data in line with the current SessionState (serialized, coalesced). */
export function syncViews(force?: SyncForce): Promise<void> {
  if (running) {
    again = strongest(again, force ?? "plain");
    return running;
  }
  running = (async () => {
    let next: SyncForce | "plain" | null = force ?? "plain";
    try {
      while (next) {
        const current: SyncForce | "plain" = next;
        again = null;
        await doSync(current === "plain" ? undefined : current);
        next = again;
      }
    } finally {
      running = null;
    }
  })();
  return running;
}

let scheduled = false;

/** Sync after the current event burst (called for every `state` event). */
export function scheduleViewSync(): void {
  if (scheduled) return;
  scheduled = true;
  queueMicrotask(() => {
    scheduled = false;
    void syncViews().catch((err: unknown) => console.warn("view sync failed", err));
  });
}

function homeSlices(ct: Volume, center: readonly number[] | null): Record<Plane, number> {
  if (center) return slicesThrough(ct.grid, center);
  const out = {} as Record<Plane, number>;
  for (const plane of ["axial", "sagittal", "coronal"] as Plane[]) out[plane] = Math.floor(sliceLayout(ct.grid, plane).count / 2);
  return out;
}

/** Isocenter (mm): the plan's, else the beams', else the first target's centre of mass. */
export function displayIsocenter(): Vec3 | null {
  const { state, beams, maskSet } = get();
  const fromPlan = isoCenterPoint(state?.plan?.iso_center);
  if (fromPlan) return fromPlan;
  if (beams?.iso_centers.length) return beams.iso_centers[0];
  const target = state?.structures.find((s) => s.type.toUpperCase() === "TARGET");
  const mask = maskSet?.masks.find((m) => m.index === target?.index);
  return mask && maskSet ? maskCenterOfMass(mask, maskSet.grid) : null;
}

async function doSync(force?: SyncForce): Promise<void> {
  const state = get().state;
  if (!state) return;
  if (!state.has.ct) {
    set({
      ct: null,
      quantities: {},
      masks: null,
      maskSet: null,
      beams: null,
      structureDetails: {},
      appliedRevisions: EMPTY_REVISIONS,
    });
    return;
  }
  const rev = state.revisions;
  const v1 = rev !== undefined;
  const applied = get().appliedRevisions;
  const next: AppliedRevisions = { ...applied, volumes: { ...applied.volumes } };
  const forceData = force === "data" || force === "all";

  // CT ------------------------------------------------------------------
  let newCt = false;
  const ctRev = rev?.volumes.ct ?? null;
  if (!get().ct || forceData || (v1 && ctRev !== applied.ct)) {
    const ct = await req("view.volume", v1 ? { name: "ct", encoding: "auto" } : { name: "ct" });
    newCt = true;
    next.ct = ctRev;
    set({ ct });
  }

  // Masks ---------------------------------------------------------------
  if (state.has.cst && (forceData || !get().maskSet || (v1 && rev.masks !== applied.masks) || (!v1 && newCt))) {
    const masks = await req("view.structure_masks", v1 ? { encoding: "crops" } : {});
    set({ maskSet: decodeMasks(masks) });
    next.masks = rev?.masks ?? null;
  } else if (!state.has.cst && get().maskSet) {
    set({ maskSet: null });
  }
  const held = get().maskSet;
  if (held) {
    const colors = new Map(state.structures.map((st) => [st.index, st.color]));
    const outdated = held.masks.some((m) => {
      const c = colors.get(m.index);
      return c !== undefined && c.some((v, i) => v !== m.color[i]);
    });
    if (outdated) {
      set({ maskSet: { ...held, masks: held.masks.map((m) => ({ ...m, color: colors.get(m.index) ?? m.color })) } });
    }
  }

  // Structure list -> default visibility (Qt default checked set) ---------
  const names = state.structures.map((s) => `${s.index}:${s.name}`).join("\u0000");
  if (names !== applied.structureNames || newCt) {
    const checked = defaultCheckedVois(state.structures);
    const visible: Record<number, boolean> = {};
    for (const st of state.structures) visible[st.index] = checked.has(st.index);
    set((s) => ({ viewer: { ...s.viewer, visible } }));
    next.structureNames = names;
  }

  // Structure details (tooltips, overlap priorities, Edit VOI) ----------
  if (v1 && state.has.cst && hasMethod("cst.get") && (rev.workspace.cst !== applied.cst || newCt)) {
    try {
      const { structures } = await req("cst.get", {});
      set({ structureDetails: Object.fromEntries(structures.map((d) => [d.index, d])) });
      next.cst = rev.workspace.cst;
    } catch (err) {
      console.warn("cst.get failed", err);
    }
  }

  // Beams ---------------------------------------------------------------
  if (hasMethod("view.beams") && (forceData || newCt || (v1 ? rev.beams !== applied.beams : force !== undefined))) {
    await fetchBeams();
    next.beams = rev?.beams ?? null;
  }

  // Home slices for a new image --------------------------------------------
  if (newCt) {
    const ct = get().ct!;
    set((s) => ({
      followIsocenter: true,
      viewer: { ...s.viewer, slices: homeSlices(ct, displayIsocenter()), view: DEFAULT_VIEW, quantityWindow: null },
    }));
  } else if (get().followIsocenter) {
    // An isocenter known only later (plan, beams, structures) still positions the view.
    const iso = displayIsocenter();
    const slices = iso ? homeSlices(get().ct!, iso) : null;
    if (slices && JSON.stringify(slices) !== JSON.stringify(get().viewer.slices)) set((s) => ({ viewer: { ...s.viewer, slices } }));
  }

  // Quantities ------------------------------------------------------------
  const groups = resultGroups(state);
  const allKeys = new Set(groups.flatMap((g) => g.components.map((c) => c.key)));
  const full = fullKeys(groups);
  const resultChanged = v1 ? rev.workspace.result !== applied.result : force !== undefined;
  const quantities: Record<string, Volume> = {};
  for (const [key, vol] of Object.entries(get().quantities)) {
    const outdated = v1 ? rev.volumes[key] !== applied.volumes[key] : resultChanged;
    if (allKeys.has(key) && !(forceData && !v1) && !outdated) quantities[key] = vol;
  }
  let active = get().viewer.activeQuantity;
  // Qt resets the shown quantity to the default after every result change (ambiguity 6).
  if (resultChanged || !active || !allKeys.has(active)) {
    active = state.results?.default ?? defaultQuantityKey(full) ?? null;
    if (active && !allKeys.has(active)) active = full[0] ?? null;
  }
  const needed = [...new Set([...(active ? [active] : []), ...full])];
  for (const key of needed) {
    const stale = !quantities[key] || (v1 ? rev.volumes[key] !== applied.volumes[key] : resultChanged);
    if (!stale) continue;
    // A snapshot key shares the revision of the array it copies (v1 amendment 14): reuse it.
    const twin = v1 ? Object.keys(quantities).find((k) => k !== key && next.volumes[k] !== undefined && next.volumes[k] === rev.volumes[key]) : undefined;
    quantities[key] = twin ? { ...quantities[twin], name: key } : await req("view.volume", { name: key });
    next.volumes[key] = rev?.volumes[key] ?? 0;
  }
  for (const key of Object.keys(next.volumes)) if (!allKeys.has(key) && key !== "ct") delete next.volumes[key];
  next.result = rev?.workspace.result ?? null;
  const previousActive = get().viewer.activeQuantity;
  set((s) => ({
    quantities,
    appliedRevisions: next,
    viewer: { ...s.viewer, activeQuantity: active, quantityWindow: active === previousActive && !resultChanged ? s.viewer.quantityWindow : null },
  }));
}

